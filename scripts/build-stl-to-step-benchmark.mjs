// mesh-bench results (platform, docs/mesh-bench.md §8) → what /stl-to-step publishes: app/lib/stl-to-step-benchmark.generated.js
// (the numbers the page and llms.txt quote) and public/benchmark/stl-to-step-own-parts.csv (one row per solid).
//
//   node scripts/build-stl-to-step-benchmark.mjs <own results.jsonl> <run id> <stl2cad commit> <pairs results.jsonl> <pairs run id>
//
// The page quotes one set (11-08, user: own and third-party in one number): our OWN parts (source generator / catalog,
// licence "own") at T2 together with the third-party parts whose authors published their STL (mesh-pairs, Treal = their
// file as published). Per part, the CSV holds our own parts only; the internal corpora (b123d, Thingiverse) never. Grades: A = the judge finds the
// same solid; B = volume within 1 % and at least 95 % of the surface area recovered (docs/mesh-bench.md §8).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const [ownPath, ownRun, commit, pairsPath, pairsRun] = process.argv.slice(2);
if (!pairsRun) throw new Error("usage: build-stl-to-step-benchmark.mjs <own results.jsonl> <run id> <stl2cad commit> <pairs results.jsonl> <pairs run id>");
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const read = (p) => readFileSync(p, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));

const TESS = "T2"; // the platform's STL download (export-formats.ts): the main score
const own = read(ownPath).filter((r) => (r.source === "generator" || r.source === "catalog") && r.tess === TESS);
const pairs = read(pairsPath).filter((r) => r.tess === "Treal"); // the authors' own STL files, as published

const ab = (r) => r.grade === "A" || r.grade === "B";
const pct = (n, d) => Math.round((1000 * n) / d) / 10;

function totals(rows) {
  const files = new Map();
  for (const r of rows) files.set(r.id, [...(files.get(r.id) ?? []), r]);
  const surfaces = rows.reduce((s, r) => s + (r.m3?.surfaces ?? 0), 0);
  const recalled = rows.reduce((s, r) => s + (r.m3?.recalled ?? 0), 0);
  const filesAB = [...files.values()].filter((v) => v.every(ab)).length;
  return {
    files: files.size,
    bodies: rows.length,
    filesAB,
    pctFilesAB: pct(filesAB, files.size),
    pctBodiesAB: pct(rows.filter(ab).length, rows.length),
    pctValid: pct(rows.filter((r) => r.m1?.ok).length, rows.length),
    pctVol1: pct(rows.filter((r) => r.volErr != null && Math.abs(r.volErr) <= 0.01).length, rows.length),
    surfaces,
    recalled,
    pctSurfaces: pct(recalled, surfaces),
  };
}

const all = [...own, ...pairs];
const CLASSES = ["C1", "C2", "C3", "C4", "C5"];
const classes = Object.fromEntries(
  CLASSES.map((c) => {
    const rows = all.filter((r) => r.class === c);
    const names = new Map();
    for (const r of rows) {
      const name = r.id.split("/")[1];
      names.set(name, (names.get(name) ?? 0) + 1);
    }
    const faces = rows.filter((r) => r.faces).map((r) => r.faces.out / Math.max(1, r.faces.truth)).sort((a, b) => a - b);
    return [c, { bodies: rows.length, pctAB: pct(rows.filter(ab).length, rows.length), pctA: pct(rows.filter((r) => r.grade === "A").length, rows.length), facesRatioMedian: Math.round(10 * (faces[Math.floor(faces.length / 2)] ?? 1)) / 10, examples: [...names].sort((a, b) => b[1] - a[1]).map(([n]) => n) }];
  }),
);

const date = new Date().toISOString().slice(0, 10);
const data = {
  date,
  mesh: TESS,
  stl2cad: commit,
  run: Number(ownRun),
  pairsRun: Number(pairsRun),
  all: totals(all),
  ownFiles: totals(own).files,
  ownBodies: own.length,
  pairFiles: totals(pairs).files,
  classes,
};
writeFileSync(
  path.join(root, "app", "lib", "stl-to-step-benchmark.generated.js"),
  `// Generated by scripts/build-stl-to-step-benchmark.mjs from mesh-bench run ${ownRun} (own parts) and ${pairsRun} (authors' meshes) —\n// do not edit; re-run the script on a newer run.\nexport const BENCHMARK = ${JSON.stringify(data, null, 2)};\n`,
);

// one row per solid of our own parts; numbers only, no files
const head = ["part", "solid", "class", "grade", "surfaces", "surfaces_recovered", "volume_error_pct", "faces_out", "faces_original", "valid_solid"];
const lines = [head.join(",")];
for (const r of [...own].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : a.body - b.body))) {
  lines.push(
    [
      r.id.replace(/^gen\//, "generator/").replace(/^cat\//, "component/"),
      r.body,
      r.class,
      r.grade ?? r.status,
      r.m3?.surfaces ?? "",
      r.m3?.recalled ?? "",
      r.volErr == null ? "" : (100 * r.volErr).toPrecision(3),
      r.faces?.out ?? "",
      r.faces?.truth ?? "",
      r.m1?.ok ? 1 : 0,
    ].join(","),
  );
}
mkdirSync(path.join(root, "public", "benchmark"), { recursive: true });
writeFileSync(path.join(root, "public", "benchmark", "stl-to-step-own-parts.csv"), lines.join("\n") + "\n");
console.log(JSON.stringify(data.all), "own files", data.ownFiles, "pair files", data.pairFiles, JSON.stringify(Object.fromEntries(Object.entries(classes).map(([c, v]) => [c, [v.bodies, v.pctAB]]))));
